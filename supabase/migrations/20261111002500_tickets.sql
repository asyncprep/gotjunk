-- Truck Team OS: tickets (admin "Tickets" page), replacing the "Projet" page.
-- Bug reports, change requests and questions for the client, filed from any admin page with the
-- Report button. Same model as the other projects, so Central (central.innodigital.ca) can read
-- them through the `central-tickets` Edge Function. spec_item is kept for history; every item in it
-- is copied below as a ticket.

create table public.ticket (
  ticket_id uuid primary key default gen_random_uuid(),
  number int generated by default as identity unique,
  type text not null check (type in ('bug', 'suggestion', 'question')),
  status text not null default 'new' check (status in ('new', 'in_progress', 'waiting', 'done', 'wont_do')),
  priority text not null default 'normal' check (priority in ('blocker', 'high', 'normal', 'low')),
  area text not null default 'other',
  title text not null check (length(trim(title)) >= 3),
  page_url text not null default '',
  description text not null default '',
  steps text not null default '',
  expected text not null default '',
  frequency text check (frequency in ('always', 'sometimes', 'once')),
  reason text not null default '',
  -- [{path, name, type}] in the private `ticket-files` bucket.
  attachments jsonb not null default '[]'::jsonb,
  -- Browser, window, language, recent pages and errors, attached by the report form.
  context jsonb not null default '{}'::jsonb,
  -- The Projet page reference (F8, I-03…) of a ticket copied from spec_item.
  spec_ref text unique,
  reporter_id uuid default auth.uid(),
  reporter_email text not null default '',
  reporter_name text not null default '',
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid,
  updated_at timestamptz not null default now(),
  updated_by uuid
);

create index on public.ticket (status);

-- Comments, and the trail of changes (kind 'event': which field, from, to).
create table public.ticket_comment (
  comment_id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.ticket on delete cascade,
  kind text not null default 'comment' check (kind in ('comment', 'event')),
  body text not null default '',
  event_field text,
  event_from text,
  event_to text,
  attachments jsonb not null default '[]'::jsonb,
  author_id uuid default auth.uid(),
  author_email text not null default '',
  author_name text not null default '',
  created_at timestamptz not null default now(),
  check (kind = 'event' or length(trim(body)) > 0)
);

create index on public.ticket_comment (ticket_id, created_at);

-- The signed-in person, for reporter and author: the employee's name, else the email.
create function public.ticket_person(p_user uuid, out email text, out name text)
language sql stable security definer set search_path = public as $$
  select coalesce(u.email, ''), coalesce(e.full_name, u.email, '')
  from auth.users u
  left join public.app_user a on a.user_id = u.id
  left join public.employee e on e.employee_id = a.employee_id
  where u.id = p_user
$$;

-- Reporter and author come from the session, never from what the browser sends.
create function public.ticket_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p record;
begin
  if auth.uid() is not null then
    select * into p from public.ticket_person(auth.uid());
    new.reporter_id := auth.uid();
    new.reporter_email := coalesce(p.email, '');
    new.reporter_name := coalesce(p.name, '');
  end if;
  if new.status in ('done', 'wont_do') and new.resolved_at is null then
    new.resolved_at := now();
  end if;
  return new;
end $$;

create trigger ticket_reporter
  before insert on public.ticket
  for each row execute function public.ticket_before_insert();

-- Closing stamps resolved_at, reopening clears it; each change is written to the trail.
create function public.ticket_before_update() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  f text;
  v_old text;
  v_new text;
begin
  new.reporter_id := old.reporter_id;
  new.reporter_email := old.reporter_email;
  new.reporter_name := old.reporter_name;
  new.number := old.number;
  if new.status is distinct from old.status then
    new.resolved_at := case when new.status in ('done', 'wont_do') then now() end;
  end if;
  foreach f in array array['status', 'priority', 'type', 'area', 'title'] loop
    v_old := to_jsonb(old) ->> f;
    v_new := to_jsonb(new) ->> f;
    if v_new is distinct from v_old then
      insert into public.ticket_comment (ticket_id, kind, event_field, event_from, event_to)
      values (new.ticket_id, 'event', f, v_old, v_new);
    end if;
  end loop;
  return new;
end $$;

create trigger ticket_changes
  before update on public.ticket
  for each row execute function public.ticket_before_update();

create function public.ticket_comment_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p record;
begin
  new.author_id := auth.uid();
  if auth.uid() is not null then
    select * into p from public.ticket_person(auth.uid());
    new.author_email := coalesce(p.email, '');
    new.author_name := coalesce(p.name, '');
  end if;
  new.created_at := now();
  return new;
end $$;

create trigger ticket_comment_author
  before insert on public.ticket_comment
  for each row execute function public.ticket_comment_before_insert();

-- A comment is activity on the ticket: it moves to the top and Central sees the change.
create function public.ticket_comment_touch() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.kind = 'comment' then
    update public.ticket set updated_at = now() where ticket_id = new.ticket_id;
  end if;
  return new;
end $$;

create trigger ticket_comment_activity
  after insert on public.ticket_comment
  for each row execute function public.ticket_comment_touch();

create trigger ticket_row_audit
  before insert or update on public.ticket
  for each row execute function public.set_row_audit_columns();

create trigger ticket_z_audit
  after insert or update or delete on public.ticket
  for each row execute function public.write_audit_log('ticket_id');

-- Everyone in the admin app files, follows up and closes tickets. Nobody deletes them, and
-- comments can't be edited afterwards.
alter table public.ticket enable row level security;
alter table public.ticket_comment enable row level security;
create policy ticket_read on public.ticket for select to authenticated using (public.is_staff());
create policy ticket_insert on public.ticket for insert to authenticated with check (public.is_staff());
create policy ticket_update on public.ticket for update to authenticated
  using (public.is_staff()) with check (public.is_staff());
create policy ticket_comment_read on public.ticket_comment for select to authenticated using (public.is_staff());
create policy ticket_comment_insert on public.ticket_comment for insert to authenticated
  with check (public.is_staff() and kind = 'comment');
grant select, insert, update on public.ticket to authenticated;
grant select, insert on public.ticket_comment to authenticated;

-- Screenshots and files, private; objects live at {random id}/{file name}.
do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit)
    values ('ticket-files', 'ticket-files', false, 52428800)
    on conflict (id) do nothing;
    execute $p$
      create policy ticket_files_read on storage.objects for select to authenticated
        using (bucket_id = 'ticket-files' and public.is_staff())
    $p$;
    execute $p$
      create policy ticket_files_insert on storage.objects for insert to authenticated
        with check (bucket_id = 'ticket-files' and public.is_staff())
    $p$;
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Every Projet item becomes a ticket, in the page's order, with its answer as the first comment.
-- ---------------------------------------------------------------------------

insert into public.ticket (type, status, priority, area, title, description, spec_ref, reporter_name,
                           resolved_at, created_at, updated_at)
select
  'question',
  case s.status when 'open' then 'new' when 'asked' then 'waiting' when 'deferred' then 'waiting' else 'done' end,
  case s.priority when 'blocker' then 'blocker' when 'pilot' then 'high' when 'v1b' then 'normal' else 'low' end,
  case
    when s.area in ('Profit share') then 'profit_share'
    when s.area in ('Jobs') then 'jobs'
    when s.area in ('Disposal') then 'disposal'
    when s.area in ('Cash', 'Tips') then 'cash'
    when s.area in ('Approvals', 'Shifts') then 'route_review'
    when s.area in ('Crew', 'Devices', 'Offline') then 'crew_app'
    when s.area in ('Integrations', 'Payments') then 'integrations'
    when s.area in ('Dispatch') then 'board'
    else 'other'
  end,
  s.ref || ' · ' || s.title,
  concat_ws(E'\n\n',
    nullif(trim(s.detail), ''),
    case when s.kind = 'inconsistency' then 'Incohérence du cahier des charges.' end,
    case when nullif(trim(s.spec_refs), '') is not null then 'Sections : ' || s.spec_refs end,
    case when nullif(trim(s.blocks), '') is not null then 'Bloque : ' || s.blocks end,
    case when nullif(trim(s.build_default), '') is not null then 'En attendant : ' || s.build_default end,
    case when s.status = 'deferred' then 'Reporté.' end),
  s.ref,
  'Projet',
  case when s.status in ('answered', 'resolved') then coalesce(s.answered_at, s.updated_at) end,
  s.created_at,
  greatest(s.updated_at, coalesce(s.answered_at, s.updated_at))
from public.spec_item s
order by s.sort_order, s.ref;

insert into public.ticket_comment (ticket_id, kind, body, author_name, created_at)
select t.ticket_id, 'comment', s.answer, 'Projet', coalesce(s.answered_at, s.updated_at)
from public.spec_item s
join public.ticket t on t.spec_ref = s.ref
where nullif(trim(s.answer), '') is not null;

-- The copy above ran as system; its comments keep the Projet dates and author.
update public.ticket_comment c set created_at = coalesce(s.answered_at, s.updated_at), author_name = 'Projet'
from public.ticket t join public.spec_item s on s.ref = t.spec_ref
where c.ticket_id = t.ticket_id and c.kind = 'comment';
